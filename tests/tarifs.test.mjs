// Grille tarifaire : contrôles de cohérence (sans navigateur).
import { quote, TARIFS, hourFactor, zoneOf } from '../web/pricing.mjs';
const results=[]; const ok=(n,c,info='')=>results.push(`${c?'PASS':'FAIL'}  ${n}${info?' — '+info:''}`);
const at=(h,m=0,day=18)=>Date.UTC(2026,10,day,h-1,m); // heure de Douala, mercredi 18/11/2026
const AKWA={lat:4.0489,lng:9.6996}, BONAM={lat:4.0950,lng:9.7400}, JAPOMA={lat:3.9950,lng:9.8150}, AKWA2={lat:4.055,lng:9.70};
const c=(o,t=at(12))=>quote(o,t);
const p1=c({service:'parcel',pickupGeo:AKWA,dropoffGeo:AKWA2,weightKg:2,vehicle:'bike'});
ok('Course courte au centre : prix plancher accessible',p1.net>=TARIFS.minimumLivraison&&p1.net<=800,p1.net+' F');
const p2=c({service:'parcel',pickupGeo:AKWA,dropoffGeo:BONAM,weightKg:3,vehicle:'bike'});
ok('Le prix augmente avec la distance',p2.net>p1.net,`${p1.net} → ${p2.net} F`);
const p3=c({service:'parcel',pickupGeo:AKWA,dropoffGeo:BONAM,weightKg:20,vehicle:'bike'});
ok('Le prix augmente avec le poids',p3.net>p2.net,`${p2.net} → ${p3.net} F`);
const p4=c({service:'parcel',pickupGeo:AKWA,dropoffGeo:BONAM,weightKg:80,vehicle:'bike'});
ok('Poids hors moto : tricycle imposé',p4.vehicle==='tricycle',p4.vehicle);
const p5=c({service:'parcel',pickupGeo:AKWA,dropoffGeo:JAPOMA,weightKg:3,vehicle:'bike'});
ok('Supplément périphérie (zone 3)',p5.zone===3&&p5.lines.some(l=>l.key==='zone'&&l.amount===TARIFS.zones[3].supplement));
ok('Zones : Akwa centre, Bonamoussadi intermédiaire, Japoma périphérie',zoneOf(AKWA)===1&&zoneOf(BONAM)===2&&zoneOf(JAPOMA)===3);
const peak=c({service:'parcel',pickupGeo:AKWA,dropoffGeo:BONAM,weightKg:3,vehicle:'bike'},at(18));
ok('Heure de pointe +15 % (18 h en semaine)',peak.hour==='peak'&&peak.net>p2.net,`${p2.net} → ${peak.net} F`);
ok('Soirée +20 % (21 h)',hourFactor(at(21)).key==='evening');
ok('Pas de majoration le dimanche à 18 h',hourFactor(at(18,0,22)).key==='normal');
const closed=c({service:'ride',pickupGeo:AKWA,dropoffGeo:BONAM,vehicle:'bike'},at(23));
ok('Fermé de 22 h à 6 h',closed.closed&&closed.errors.includes('closed'));
ok('Prix arrondis au 50 F',[p1,p2,p3,p4,p5,peak].every(q=>q.net%50===0));
const l1=c({service:'laundry',pickupGeo:BONAM,laundry:{items:{shirt:3,trousers:2}}});
ok('Pressing : articles + collecte',l1.lines.find(l=>l.key==='items').amount===3*400+2*500&&l1.lines.some(l=>l.key==='collect'),l1.net+' F');
const l2=c({service:'laundry',pickupGeo:BONAM,laundry:{kg:6}});
ok('Pressing : 1 kg offert dès 5 kg',l2.lines.some(l=>l.key==='kgFree'&&l.amount===-1300));
const l3=c({service:'laundry',pickupGeo:BONAM,laundry:{kg:10}});
ok('Pressing : collecte offerte dès 10 kg',l3.lines.some(l=>l.key==='collectFree'));
const l4=c({service:'laundry',pickupGeo:BONAM,laundry:{items:{shirt:2},speed:'express'}});
ok('Pressing express plus cher que standard',l4.lines.find(l=>l.key==='items').amount>800);
ok('Pressing vide refusé',c({service:'laundry',pickupGeo:BONAM,laundry:{}}).errors.includes('empty'));
ok('Frais de collecte plafonnés',c({service:'laundry',pickupGeo:JAPOMA,laundry:{items:{shirt:1}}}).lines.find(l=>l.key==='collect').amount<=TARIFS.pressing.collecteMax);
const e1=c({service:'errand',pickupGeo:AKWA,dropoffGeo:BONAM,errand:{list:[{name:'Riz',qty:2,price:6000}],load:'light'}});
ok('Courses : articles + frais de service + livraison',e1.articles===12000&&e1.lines.some(l=>l.key==='service')&&e1.lines.some(l=>l.key==='delivery'),e1.net+' F');
ok('Courses : frais de service plafonnés',c({service:'errand',pickupGeo:AKWA,dropoffGeo:BONAM,errand:{list:[{name:'TV',qty:1,price:400000}],advance:false}}).lines.find(l=>l.key==='service').amount===TARIFS.courses.fraisMax);
ok('Courses : avance limitée à 50 000 F',c({service:'errand',pickupGeo:AKWA,dropoffGeo:BONAM,errand:{list:[{name:'TV',qty:1,price:60000}],advance:true}}).errors.includes('advance'));
ok('Courses lourdes en tricycle',c({service:'errand',pickupGeo:AKWA,dropoffGeo:BONAM,errand:{list:[{name:'Ciment',qty:1,price:5000}],load:'heavy'}}).vehicle==='tricycle');
const r1=c({service:'ride',pickupGeo:AKWA,dropoffGeo:BONAM,vehicle:'bike',ride:{passengers:1}});
const r2=c({service:'ride',pickupGeo:AKWA,dropoffGeo:BONAM,vehicle:'bike',ride:{passengers:3}});
ok('Moto-taxi accessible (≈ 9 km sous 1 000 F)',r1.net<1000,r1.net+' F');
ok('Plusieurs passagers : voiture',r2.vehicle==='car'&&r2.net>r1.net,r2.net+' F');
console.log(results.join('\n'));
if(results.some(r=>r.startsWith('FAIL'))) process.exit(1);
